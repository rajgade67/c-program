#include <stdio.h>

int main ()
{
    char ch = 'A';
    int i = 11;
    float f = 90.90f;
    double d = 78.7890;

    printf("values of all variables:\n");
    printf("Character = %c\n", ch);
    printf("Integer = %d\n", i);
    printf("Float = %f\n", f);
    printf("Double = %lf\n", d);

    return 0;
}